-- Q10 — volume e formato das linhas no período
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP, DATE '1900-01-01' AS INI, DATE '1900-01-31' AS FIM FROM RDB$DATABASE)
SELECT
    COUNT(*) AS LINHAS,
    COUNT(L.CHAVELCTOCTB) AS LINHAS_COM_CHAVE,
    COUNT(DISTINCT L.CHAVELCTOCTB) AS CHAVES_DISTINTAS,
    SUM(CASE WHEN L.CONTACTBDEB IS NOT NULL AND L.CONTACTBCRED IS NOT NULL THEN 1 ELSE 0 END) AS LINHAS_DEB_E_CRED,
    SUM(CASE WHEN L.CONTACTBDEB IS NOT NULL AND L.CONTACTBCRED IS NULL THEN 1 ELSE 0 END) AS LINHAS_SO_DEB,
    SUM(CASE WHEN L.CONTACTBDEB IS NULL AND L.CONTACTBCRED IS NOT NULL THEN 1 ELSE 0 END) AS LINHAS_SO_CRED,
    SUM(CASE WHEN L.CONTACTBDEB IS NULL AND L.CONTACTBCRED IS NULL THEN 1 ELSE 0 END) AS LINHAS_SEM_CONTA,
    SUM(CASE WHEN L.CONTACTBDEB = L.CONTACTBCRED THEN 1 ELSE 0 END) AS LINHAS_DEB_IGUAL_CRED,
    MIN(L.DATALCTOCTB) AS PRIMEIRA_DATA,
    MAX(L.DATALCTOCTB) AS ULTIMA_DATA
FROM LCTOCTB L
CROSS JOIN P
WHERE L.CODIGOEMPRESA = P.EMP
  AND L.DATALCTOCTB BETWEEN P.INI AND P.FIM;

-- Q11 — sinal de VALORLCTOCTB no período, por formato da linha (#449)
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP, DATE '1900-01-01' AS INI, DATE '1900-01-31' AS FIM FROM RDB$DATABASE)
SELECT
    CASE
        WHEN L.CONTACTBDEB IS NOT NULL AND L.CONTACTBCRED IS NOT NULL THEN 'DEB_E_CRED'
        WHEN L.CONTACTBDEB IS NOT NULL THEN 'SO_DEB'
        WHEN L.CONTACTBCRED IS NOT NULL THEN 'SO_CRED'
        ELSE 'SEM_CONTA'
    END AS FORMATO,
    CASE
        WHEN L.VALORLCTOCTB IS NULL THEN 'NULO'
        WHEN L.VALORLCTOCTB < 0 THEN 'NEGATIVO'
        WHEN L.VALORLCTOCTB = 0 THEN 'ZERO'
        ELSE 'POSITIVO'
    END AS SINAL,
    COUNT(*) AS LINHAS,
    MIN(L.DATALCTOCTB) AS PRIMEIRA_DATA,
    MAX(L.DATALCTOCTB) AS ULTIMA_DATA
FROM LCTOCTB L
CROSS JOIN P
WHERE L.CODIGOEMPRESA = P.EMP
  AND L.DATALCTOCTB BETWEEN P.INI AND P.FIM
GROUP BY 1, 2
ORDER BY 1, 2;

-- Q12 — linhas negativas por ano/mês, todo o histórico da empresa (#449)
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP FROM RDB$DATABASE)
SELECT
    EXTRACT(YEAR FROM L.DATALCTOCTB) AS ANO,
    EXTRACT(MONTH FROM L.DATALCTOCTB) AS MES,
    COUNT(*) AS LINHAS,
    SUM(CASE WHEN L.VALORLCTOCTB < 0 THEN 1 ELSE 0 END) AS LINHAS_NEGATIVAS
FROM LCTOCTB L
CROSS JOIN P
WHERE L.CODIGOEMPRESA = P.EMP
GROUP BY 1, 2
ORDER BY 1, 2;

-- Q13 — negativos no banco inteiro, por ano (sem identificar empresa) (#449)
--       Percorre LCTOCTB de todas as empresas. Só roda depois de substituir o
--       marcador da empresa: com EMP = -1 não lê nenhuma linha.
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP FROM RDB$DATABASE)
SELECT
    EXTRACT(YEAR FROM L.DATALCTOCTB) AS ANO,
    COUNT(*) AS LINHAS,
    SUM(CASE WHEN L.VALORLCTOCTB < 0 THEN 1 ELSE 0 END) AS LINHAS_NEGATIVAS,
    COUNT(DISTINCT CASE WHEN L.VALORLCTOCTB < 0 THEN L.CODIGOEMPRESA END) AS QTD_EMPRESAS_COM_NEGATIVO
FROM LCTOCTB L
CROSS JOIN P
WHERE P.EMP <> -1
GROUP BY 1
ORDER BY 1;

-- Q14 — cardinalidade de CHAVELCTOCTB: quantas linhas por chave
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP, DATE '1900-01-01' AS INI, DATE '1900-01-31' AS FIM FROM RDB$DATABASE)
SELECT G.LINHAS_POR_CHAVE, COUNT(*) AS QTD_CHAVES
FROM (
    SELECT L.CHAVELCTOCTB, COUNT(*) AS LINHAS_POR_CHAVE
    FROM LCTOCTB L
    CROSS JOIN P
    WHERE L.CODIGOEMPRESA = P.EMP
      AND L.DATALCTOCTB BETWEEN P.INI AND P.FIM
    GROUP BY L.CHAVELCTOCTB
) G
GROUP BY G.LINHAS_POR_CHAVE
ORDER BY G.LINHAS_POR_CHAVE;

-- Q15 — composição das chaves: linhas DEB_E_CRED / SO_DEB / SO_CRED por chave
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP, DATE '1900-01-01' AS INI, DATE '1900-01-31' AS FIM FROM RDB$DATABASE)
SELECT G.DEB_E_CRED, G.SO_DEB, G.SO_CRED, G.SEM_CONTA, COUNT(*) AS QTD_CHAVES
FROM (
    SELECT
        L.CHAVELCTOCTB,
        SUM(CASE WHEN L.CONTACTBDEB IS NOT NULL AND L.CONTACTBCRED IS NOT NULL THEN 1 ELSE 0 END) AS DEB_E_CRED,
        SUM(CASE WHEN L.CONTACTBDEB IS NOT NULL AND L.CONTACTBCRED IS NULL THEN 1 ELSE 0 END) AS SO_DEB,
        SUM(CASE WHEN L.CONTACTBDEB IS NULL AND L.CONTACTBCRED IS NOT NULL THEN 1 ELSE 0 END) AS SO_CRED,
        SUM(CASE WHEN L.CONTACTBDEB IS NULL AND L.CONTACTBCRED IS NULL THEN 1 ELSE 0 END) AS SEM_CONTA
    FROM LCTOCTB L
    CROSS JOIN P
    WHERE L.CODIGOEMPRESA = P.EMP
      AND L.DATALCTOCTB BETWEEN P.INI AND P.FIM
    GROUP BY L.CHAVELCTOCTB
) G
GROUP BY G.DEB_E_CRED, G.SO_DEB, G.SO_CRED, G.SEM_CONTA
ORDER BY 5 DESC;

-- Q16 — chaves com linhas de um lado só: soma dos débitos fecha com a dos créditos?
--       (retorna apenas contagens de chaves; nenhum valor)
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP, DATE '1900-01-01' AS INI, DATE '1900-01-31' AS FIM FROM RDB$DATABASE)
SELECT
    CASE WHEN G.SOMA_SO_DEB = G.SOMA_SO_CRED THEN 'FECHA' ELSE 'NAO_FECHA' END AS EQUILIBRIO,
    COUNT(*) AS QTD_CHAVES
FROM (
    SELECT
        L.CHAVELCTOCTB,
        SUM(CASE WHEN L.CONTACTBDEB IS NOT NULL AND L.CONTACTBCRED IS NULL THEN L.VALORLCTOCTB ELSE 0 END) AS SOMA_SO_DEB,
        SUM(CASE WHEN L.CONTACTBDEB IS NULL AND L.CONTACTBCRED IS NOT NULL THEN L.VALORLCTOCTB ELSE 0 END) AS SOMA_SO_CRED,
        SUM(CASE WHEN (L.CONTACTBDEB IS NULL AND L.CONTACTBCRED IS NOT NULL)
                   OR (L.CONTACTBDEB IS NOT NULL AND L.CONTACTBCRED IS NULL) THEN 1 ELSE 0 END) AS LINHAS_UM_LADO
    FROM LCTOCTB L
    CROSS JOIN P
    WHERE L.CODIGOEMPRESA = P.EMP
      AND L.DATALCTOCTB BETWEEN P.INI AND P.FIM
    GROUP BY L.CHAVELCTOCTB
) G
WHERE G.LINHAS_UM_LADO > 0
GROUP BY 1
ORDER BY 1;

-- Q17 — a mesma chave aparece com mais de uma data dentro da empresa?
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP, DATE '1900-01-01' AS INI, DATE '1900-01-31' AS FIM FROM RDB$DATABASE)
SELECT G.DATAS_POR_CHAVE, COUNT(*) AS QTD_CHAVES
FROM (
    SELECT L.CHAVELCTOCTB, COUNT(DISTINCT L.DATALCTOCTB) AS DATAS_POR_CHAVE
    FROM LCTOCTB L
    CROSS JOIN P
    WHERE L.CODIGOEMPRESA = P.EMP
      AND L.DATALCTOCTB BETWEEN P.INI AND P.FIM
    GROUP BY L.CHAVELCTOCTB
) G
GROUP BY G.DATAS_POR_CHAVE
ORDER BY 1;

-- Q18 — as chaves da empresa no período também aparecem em outras empresas?
--       (contagem apenas; pode ser lenta em bancos grandes, ver runbook)
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP, DATE '1900-01-01' AS INI, DATE '1900-01-31' AS FIM FROM RDB$DATABASE)
SELECT COUNT(*) AS CHAVES_EM_OUTRA_EMPRESA
FROM (
    SELECT DISTINCT L.CHAVELCTOCTB
    FROM LCTOCTB L
    CROSS JOIN P
    WHERE L.CODIGOEMPRESA = P.EMP
      AND L.DATALCTOCTB BETWEEN P.INI AND P.FIM
) K
WHERE EXISTS (
    SELECT 1 FROM LCTOCTB O
    CROSS JOIN P
    WHERE O.CHAVELCTOCTB = K.CHAVELCTOCTB
      AND O.CODIGOEMPRESA <> P.EMP
);

-- Q19 — meses com movimento em todo o histórico da empresa (lacunas de cobertura)
