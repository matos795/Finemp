ORDER BY 1;

-- Q22 — universos: plano x contas observadas no período
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP, DATE '1900-01-01' AS INI, DATE '1900-01-31' AS FIM FROM RDB$DATABASE),
OBS AS (
    SELECT L.CONTACTBDEB AS CONTA
    FROM LCTOCTB L CROSS JOIN P
    WHERE L.CODIGOEMPRESA = P.EMP AND L.DATALCTOCTB BETWEEN P.INI AND P.FIM AND L.CONTACTBDEB IS NOT NULL
    UNION
    SELECT L.CONTACTBCRED
    FROM LCTOCTB L CROSS JOIN P
    WHERE L.CODIGOEMPRESA = P.EMP AND L.DATALCTOCTB BETWEEN P.INI AND P.FIM AND L.CONTACTBCRED IS NOT NULL
)
SELECT
    (SELECT COUNT(DISTINCT PE.CONTACTB) FROM PLANOESPEC PE CROSS JOIN P WHERE PE.CODIGOEMPRESA = P.EMP) AS CONTAS_NO_PLANO,
    (SELECT COUNT(*) FROM OBS) AS CONTAS_OBSERVADAS_NO_PERIODO,
    (SELECT COUNT(*) FROM OBS O WHERE EXISTS (
        SELECT 1 FROM PLANOESPEC PE CROSS JOIN P
        WHERE PE.CODIGOEMPRESA = P.EMP AND PE.CONTACTB = O.CONTA)) AS OBSERVADAS_E_NO_PLANO,
    (SELECT COUNT(*) FROM OBS O WHERE NOT EXISTS (
        SELECT 1 FROM PLANOESPEC PE CROSS JOIN P
        WHERE PE.CODIGOEMPRESA = P.EMP AND PE.CONTACTB = O.CONTA)) AS OBSERVADAS_FORA_DO_PLANO,
    (SELECT COUNT(DISTINCT PE.CONTACTB) FROM PLANOESPEC PE CROSS JOIN P
      WHERE PE.CODIGOEMPRESA = P.EMP
        AND NOT EXISTS (SELECT 1 FROM OBS O WHERE O.CONTA = PE.CONTACTB)) AS NO_PLANO_SEM_MOVIMENTO
FROM RDB$DATABASE;

-- Q23 — lados que o join atual com PLANOESPEC descartaria no período
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP, DATE '1900-01-01' AS INI, DATE '1900-01-31' AS FIM FROM RDB$DATABASE)
SELECT
    SUM(CASE WHEN L.CONTACTBDEB IS NULL THEN 1 ELSE 0 END) AS LADO_DEB_NULO,
    SUM(CASE WHEN L.CONTACTBDEB IS NOT NULL AND NOT EXISTS (
            SELECT 1 FROM PLANOESPEC PE WHERE PE.CODIGOEMPRESA = L.CODIGOEMPRESA AND PE.CONTACTB = L.CONTACTBDEB)
        THEN 1 ELSE 0 END) AS LADO_DEB_SEM_CONTA_NO_PLANO,
    SUM(CASE WHEN L.CONTACTBCRED IS NULL THEN 1 ELSE 0 END) AS LADO_CRED_NULO,
    SUM(CASE WHEN L.CONTACTBCRED IS NOT NULL AND NOT EXISTS (
            SELECT 1 FROM PLANOESPEC PE WHERE PE.CODIGOEMPRESA = L.CODIGOEMPRESA AND PE.CONTACTB = L.CONTACTBCRED)
        THEN 1 ELSE 0 END) AS LADO_CRED_SEM_CONTA_NO_PLANO
FROM LCTOCTB L
CROSS JOIN P
WHERE L.CODIGOEMPRESA = P.EMP
  AND L.DATALCTOCTB BETWEEN P.INI AND P.FIM;

-- Q24 — formato de CLASSIFCONTA: comprimento e quantidade de pontos (sem conteúdo)
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP FROM RDB$DATABASE)
SELECT
