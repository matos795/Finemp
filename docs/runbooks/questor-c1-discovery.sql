-- Q20 — tamanho do plano da empresa e unicidade de CONTACTB
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP FROM RDB$DATABASE)
SELECT
    COUNT(*) AS LINHAS_PLANO,
    COUNT(DISTINCT PE.CONTACTB) AS CONTAS_DISTINTAS,
    COUNT(DISTINCT PE.CLASSIFCONTA) AS CLASSIFICACOES_DISTINTAS,
