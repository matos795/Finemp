-- Q01 — tabelas e views de usuário, com quantidade de colunas
SELECT
    TRIM(R.RDB$RELATION_NAME) AS TABELA,
    CASE WHEN R.RDB$VIEW_BLR IS NULL THEN 'TABLE' ELSE 'VIEW' END AS TIPO,
    (SELECT COUNT(*) FROM RDB$RELATION_FIELDS RF
      WHERE RF.RDB$RELATION_NAME = R.RDB$RELATION_NAME) AS QTD_COLUNAS
FROM RDB$RELATIONS R
WHERE COALESCE(R.RDB$SYSTEM_FLAG, 0) = 0
ORDER BY 1;

-- Q02 — tabelas cujo NOME contém um dos padrões
SELECT
    TRIM(PD.PADRAO) AS PADRAO,
    TRIM(R.RDB$RELATION_NAME) AS TABELA,
    CASE WHEN R.RDB$VIEW_BLR IS NULL THEN 'TABLE' ELSE 'VIEW' END AS TIPO
FROM RDB$RELATIONS R
JOIN (
          SELECT 'SALD' AS PADRAO FROM RDB$DATABASE
    UNION ALL SELECT 'INICIAL' FROM RDB$DATABASE
    UNION ALL SELECT 'ANTERIOR' FROM RDB$DATABASE
    UNION ALL SELECT 'DOC' FROM RDB$DATABASE
    UNION ALL SELECT 'NUM' FROM RDB$DATABASE
    UNION ALL SELECT 'HIST' FROM RDB$DATABASE
    UNION ALL SELECT 'ENCERR' FROM RDB$DATABASE
    UNION ALL SELECT 'FECH' FROM RDB$DATABASE
    UNION ALL SELECT 'LOTE' FROM RDB$DATABASE
    UNION ALL SELECT 'CENTRO' FROM RDB$DATABASE
    UNION ALL SELECT 'CUST' FROM RDB$DATABASE
    UNION ALL SELECT 'PART' FROM RDB$DATABASE
    UNION ALL SELECT 'FORNE' FROM RDB$DATABASE
    UNION ALL SELECT 'CLIENT' FROM RDB$DATABASE
    UNION ALL SELECT 'CONTR' FROM RDB$DATABASE
    UNION ALL SELECT 'CHAVE' FROM RDB$DATABASE
    UNION ALL SELECT 'LCTO' FROM RDB$DATABASE
    UNION ALL SELECT 'PLANO' FROM RDB$DATABASE
    UNION ALL SELECT 'CTB' FROM RDB$DATABASE
) PD ON R.RDB$RELATION_NAME CONTAINING TRIM(PD.PADRAO)
WHERE COALESCE(R.RDB$SYSTEM_FLAG, 0) = 0
ORDER BY 1, 2;

-- Q03 — colunas cujo NOME contém um dos padrões (tabela, coluna, tipo)
SELECT
    TRIM(PD.PADRAO) AS PADRAO,
    TRIM(RF.RDB$RELATION_NAME) AS TABELA,
    TRIM(RF.RDB$FIELD_NAME) AS COLUNA,
    CASE F.RDB$FIELD_TYPE
        WHEN 7 THEN CASE F.RDB$FIELD_SUB_TYPE WHEN 1 THEN 'NUMERIC' WHEN 2 THEN 'DECIMAL' ELSE 'SMALLINT' END
        WHEN 8 THEN CASE F.RDB$FIELD_SUB_TYPE WHEN 1 THEN 'NUMERIC' WHEN 2 THEN 'DECIMAL' ELSE 'INTEGER' END
        WHEN 16 THEN CASE F.RDB$FIELD_SUB_TYPE WHEN 1 THEN 'NUMERIC' WHEN 2 THEN 'DECIMAL' ELSE 'BIGINT' END
        WHEN 10 THEN 'FLOAT' WHEN 27 THEN 'DOUBLE PRECISION'
        WHEN 12 THEN 'DATE' WHEN 13 THEN 'TIME' WHEN 35 THEN 'TIMESTAMP'
        WHEN 14 THEN 'CHAR' WHEN 37 THEN 'VARCHAR' WHEN 40 THEN 'CSTRING'
        WHEN 261 THEN 'BLOB'
        ELSE 'TIPO_' || F.RDB$FIELD_TYPE
    END AS TIPO,
    F.RDB$FIELD_PRECISION AS PRECISAO,
    -F.RDB$FIELD_SCALE AS ESCALA,
    COALESCE(F.RDB$CHARACTER_LENGTH, F.RDB$FIELD_LENGTH) AS TAMANHO,
    CASE WHEN COALESCE(RF.RDB$NULL_FLAG, F.RDB$NULL_FLAG, 0) = 1 THEN 'NOT NULL' ELSE 'NULL' END AS NULO
FROM RDB$RELATION_FIELDS RF
JOIN RDB$RELATIONS R ON R.RDB$RELATION_NAME = RF.RDB$RELATION_NAME
JOIN RDB$FIELDS F ON F.RDB$FIELD_NAME = RF.RDB$FIELD_SOURCE
JOIN (
          SELECT 'SALD' AS PADRAO FROM RDB$DATABASE
    UNION ALL SELECT 'INICIAL' FROM RDB$DATABASE
    UNION ALL SELECT 'ANTERIOR' FROM RDB$DATABASE
    UNION ALL SELECT 'DOC' FROM RDB$DATABASE
    UNION ALL SELECT 'NUM' FROM RDB$DATABASE
    UNION ALL SELECT 'HIST' FROM RDB$DATABASE
    UNION ALL SELECT 'ENCERR' FROM RDB$DATABASE
    UNION ALL SELECT 'FECH' FROM RDB$DATABASE
    UNION ALL SELECT 'LOTE' FROM RDB$DATABASE
    UNION ALL SELECT 'CENTRO' FROM RDB$DATABASE
    UNION ALL SELECT 'CUST' FROM RDB$DATABASE
    UNION ALL SELECT 'PART' FROM RDB$DATABASE
    UNION ALL SELECT 'FORNE' FROM RDB$DATABASE
    UNION ALL SELECT 'CLIENT' FROM RDB$DATABASE
    UNION ALL SELECT 'CONTR' FROM RDB$DATABASE
    UNION ALL SELECT 'CHAVE' FROM RDB$DATABASE
    UNION ALL SELECT 'CCUSTO' FROM RDB$DATABASE
    UNION ALL SELECT 'ANALIT' FROM RDB$DATABASE
    UNION ALL SELECT 'SINTET' FROM RDB$DATABASE
    UNION ALL SELECT 'NATUR' FROM RDB$DATABASE
    UNION ALL SELECT 'NIVEL' FROM RDB$DATABASE
    UNION ALL SELECT 'GRAU' FROM RDB$DATABASE
    UNION ALL SELECT 'INATIV' FROM RDB$DATABASE
    UNION ALL SELECT 'SITUAC' FROM RDB$DATABASE
    UNION ALL SELECT 'EXCLU' FROM RDB$DATABASE
    UNION ALL SELECT 'CANCEL' FROM RDB$DATABASE
    UNION ALL SELECT 'ESTORN' FROM RDB$DATABASE
    UNION ALL SELECT 'ATUALIZ' FROM RDB$DATABASE
    UNION ALL SELECT 'ORIGEM' FROM RDB$DATABASE
    UNION ALL SELECT 'SEQ' FROM RDB$DATABASE
) PD ON RF.RDB$FIELD_NAME CONTAINING TRIM(PD.PADRAO)
WHERE COALESCE(R.RDB$SYSTEM_FLAG, 0) = 0
ORDER BY 1, 2, 3;

-- Q04 — todas as colunas de LCTOCTB e PLANOESPEC (posição, tipo, nulidade)
SELECT
    TRIM(RF.RDB$RELATION_NAME) AS TABELA,
    RF.RDB$FIELD_POSITION AS POSICAO,
    TRIM(RF.RDB$FIELD_NAME) AS COLUNA,
    CASE F.RDB$FIELD_TYPE
        WHEN 7 THEN CASE F.RDB$FIELD_SUB_TYPE WHEN 1 THEN 'NUMERIC' WHEN 2 THEN 'DECIMAL' ELSE 'SMALLINT' END
        WHEN 8 THEN CASE F.RDB$FIELD_SUB_TYPE WHEN 1 THEN 'NUMERIC' WHEN 2 THEN 'DECIMAL' ELSE 'INTEGER' END
        WHEN 16 THEN CASE F.RDB$FIELD_SUB_TYPE WHEN 1 THEN 'NUMERIC' WHEN 2 THEN 'DECIMAL' ELSE 'BIGINT' END
        WHEN 10 THEN 'FLOAT' WHEN 27 THEN 'DOUBLE PRECISION'
        WHEN 12 THEN 'DATE' WHEN 13 THEN 'TIME' WHEN 35 THEN 'TIMESTAMP'
        WHEN 14 THEN 'CHAR' WHEN 37 THEN 'VARCHAR' WHEN 40 THEN 'CSTRING'
        WHEN 261 THEN 'BLOB'
        ELSE 'TIPO_' || F.RDB$FIELD_TYPE
    END AS TIPO,
    F.RDB$FIELD_PRECISION AS PRECISAO,
    -F.RDB$FIELD_SCALE AS ESCALA,
    COALESCE(F.RDB$CHARACTER_LENGTH, F.RDB$FIELD_LENGTH) AS TAMANHO,
    CASE WHEN COALESCE(RF.RDB$NULL_FLAG, F.RDB$NULL_FLAG, 0) = 1 THEN 'NOT NULL' ELSE 'NULL' END AS NULO,
    TRIM(RF.RDB$FIELD_SOURCE) AS DOMINIO
FROM RDB$RELATION_FIELDS RF
JOIN RDB$FIELDS F ON F.RDB$FIELD_NAME = RF.RDB$FIELD_SOURCE
WHERE RF.RDB$RELATION_NAME IN ('LCTOCTB', 'PLANOESPEC')
ORDER BY 1, 2;

-- Q05 — chaves primárias e únicas declaradas em LCTOCTB e PLANOESPEC
SELECT
    TRIM(RC.RDB$RELATION_NAME) AS TABELA,
    TRIM(RC.RDB$CONSTRAINT_TYPE) AS RESTRICAO,
    TRIM(RC.RDB$CONSTRAINT_NAME) AS NOME,
    S.RDB$FIELD_POSITION AS ORDEM,
    TRIM(S.RDB$FIELD_NAME) AS COLUNA
FROM RDB$RELATION_CONSTRAINTS RC
JOIN RDB$INDEX_SEGMENTS S ON S.RDB$INDEX_NAME = RC.RDB$INDEX_NAME
WHERE RC.RDB$RELATION_NAME IN ('LCTOCTB', 'PLANOESPEC')
  AND RC.RDB$CONSTRAINT_TYPE IN ('PRIMARY KEY', 'UNIQUE')
ORDER BY 1, 2, 3, 4;

-- Q06 — todos os índices de LCTOCTB e PLANOESPEC (únicos ou não)
SELECT
    TRIM(I.RDB$RELATION_NAME) AS TABELA,
    TRIM(I.RDB$INDEX_NAME) AS INDICE,
    COALESCE(I.RDB$UNIQUE_FLAG, 0) AS UNICO,
    COALESCE(I.RDB$INDEX_INACTIVE, 0) AS INATIVO,
    S.RDB$FIELD_POSITION AS ORDEM,
    TRIM(S.RDB$FIELD_NAME) AS COLUNA
FROM RDB$INDICES I
JOIN RDB$INDEX_SEGMENTS S ON S.RDB$INDEX_NAME = I.RDB$INDEX_NAME
WHERE I.RDB$RELATION_NAME IN ('LCTOCTB', 'PLANOESPEC')
ORDER BY 1, 2, 5;

-- Q07 — chaves estrangeiras declaradas entre tabelas de usuário
--       (coluna da tabela filha -> coluna da tabela referenciada)
SELECT
    TRIM(FK.RDB$RELATION_NAME) AS TABELA_FILHA,
    TRIM(FS.RDB$FIELD_NAME) AS COLUNA_FILHA,
    TRIM(PK.RDB$RELATION_NAME) AS TABELA_REFERENCIADA,
    TRIM(PS.RDB$FIELD_NAME) AS COLUNA_REFERENCIADA,
    TRIM(FK.RDB$CONSTRAINT_NAME) AS RESTRICAO,
    FS.RDB$FIELD_POSITION AS ORDEM
FROM RDB$RELATION_CONSTRAINTS FK
JOIN RDB$REF_CONSTRAINTS RC ON RC.RDB$CONSTRAINT_NAME = FK.RDB$CONSTRAINT_NAME
JOIN RDB$RELATION_CONSTRAINTS PK ON PK.RDB$CONSTRAINT_NAME = RC.RDB$CONST_NAME_UQ
JOIN RDB$INDEX_SEGMENTS FS ON FS.RDB$INDEX_NAME = FK.RDB$INDEX_NAME
JOIN RDB$INDEX_SEGMENTS PS ON PS.RDB$INDEX_NAME = PK.RDB$INDEX_NAME
                          AND PS.RDB$FIELD_POSITION = FS.RDB$FIELD_POSITION
WHERE FK.RDB$CONSTRAINT_TYPE = 'FOREIGN KEY'
ORDER BY 1, 5, 6;

-- Q08 — triggers ligados a LCTOCTB e PLANOESPEC (somente nome e tipo, sem código)
SELECT
    TRIM(T.RDB$RELATION_NAME) AS TABELA,
    TRIM(T.RDB$TRIGGER_NAME) AS GATILHO,
    T.RDB$TRIGGER_TYPE AS TIPO_GATILHO,
    COALESCE(T.RDB$TRIGGER_INACTIVE, 0) AS INATIVO
