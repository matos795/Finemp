CROSS JOIN P
WHERE PE.CODIGOEMPRESA = P.EMP;

-- Q21 — CONTACTB repetido no plano da mesma empresa (o join do reader duplicaria linhas)
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP FROM RDB$DATABASE)
SELECT G.LINHAS_POR_CONTA, COUNT(*) AS QTD_CONTAS
FROM (
    SELECT PE.CONTACTB, COUNT(*) AS LINHAS_POR_CONTA
