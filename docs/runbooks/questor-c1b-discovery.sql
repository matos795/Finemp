-- Q53 — contas com saldo x TIPOCONTA x movimento no período
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP, DATE '1900-01-01' AS INI, DATE '1900-01-31' AS FIM FROM RDB$DATABASE),
OBS AS (
    SELECT L.CONTACTBDEB AS CONTA FROM LCTOCTB L CROSS JOIN P
    WHERE L.CODIGOEMPRESA = P.EMP AND L.DATALCTOCTB BETWEEN P.INI AND P.FIM AND L.CONTACTBDEB IS NOT NULL
    UNION
    SELECT L.CONTACTBCRED FROM LCTOCTB L CROSS JOIN P
    WHERE L.CODIGOEMPRESA = P.EMP AND L.DATALCTOCTB BETWEEN P.INI AND P.FIM AND L.CONTACTBCRED IS NOT NULL
)
SELECT X.TIPOCONTA, X.SALDO_MENSAL, X.SALDO_CTB, X.MOVIMENTO, COUNT(*) AS QTD_CONTAS
FROM (
    SELECT PE.TIPOCONTA,
        CASE WHEN EXISTS (SELECT 1 FROM SALDOCTBMENSAL S WHERE S.CODIGOEMPRESA = PE.CODIGOEMPRESA AND S.CONTACTB = PE.CONTACTB)
             THEN 'COM_SALDO_MENSAL' ELSE 'SEM_SALDO_MENSAL' END AS SALDO_MENSAL,
        CASE WHEN EXISTS (SELECT 1 FROM SALDOCTB S WHERE S.CODIGOEMPRESA = PE.CODIGOEMPRESA AND S.CONTACTB = PE.CONTACTB)
             THEN 'COM_SALDOCTB' ELSE 'SEM_SALDOCTB' END AS SALDO_CTB,
