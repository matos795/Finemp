    (SELECT COUNT(*) FROM PLANOESPECPLANODRE X CROSS JOIN P WHERE X.CODIGOEMPRESA = P.EMP) AS LINHAS_PLANODRE,
    (SELECT COUNT(DISTINCT X.CONTACTB) FROM PLANOESPECPLANODRE X CROSS JOIN P WHERE X.CODIGOEMPRESA = P.EMP) AS CONTAS_PLANODRE,
    (SELECT COUNT(DISTINCT X.CODIGODRE) FROM PLANOESPECPLANODRE X CROSS JOIN P WHERE X.CODIGOEMPRESA = P.EMP) AS CODIGODRE_PLANODRE,
    (SELECT COUNT(*) FROM PLANOESPECPLANODRE X CROSS JOIN P
      JOIN PLANOESPEC PE ON PE.CODIGOEMPRESA = X.CODIGOEMPRESA AND PE.CONTACTB = X.CONTACTB
      WHERE X.CODIGOEMPRESA = P.EMP AND PE.CODIGODRE = X.CODIGODRE AND PE.CONTADRE = X.CONTADRE) AS IGUAL_PLANOESPEC,
    (SELECT COUNT(*) FROM PLANOESPECPLANODRE X CROSS JOIN P
      JOIN PLANOESPEC PE ON PE.CODIGOEMPRESA = X.CODIGOEMPRESA AND PE.CONTACTB = X.CONTACTB
      WHERE X.CODIGOEMPRESA = P.EMP
        AND (PE.CODIGODRE IS NULL OR PE.CONTADRE IS NULL OR PE.CODIGODRE <> X.CODIGODRE OR PE.CONTADRE <> X.CONTADRE)) AS DIFERENTE_PLANOESPEC
