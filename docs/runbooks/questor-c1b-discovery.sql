-- Q72 — qual campo agrupa partidas? Para cada candidato, grupos cujo total
--       a débito fecha com o total a crédito (só contagem de grupos).
--       Linha DEB_E_CRED entra nos dois lados; uma linha só de um lado não.
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP, DATE '1900-01-01' AS INI, DATE '1900-01-31' AS FIM FROM RDB$DATABASE),
L AS (
    SELECT X.* FROM LCTOCTB X CROSS JOIN P
    WHERE X.CODIGOEMPRESA = P.EMP AND X.DATALCTOCTB BETWEEN P.INI AND P.FIM
),
G AS (
    SELECT 'CODIGOLOTECTB' AS CAMPO, CAST(L.CODIGOLOTECTB AS VARCHAR(40)) AS GRUPO,
           SUM(CASE WHEN L.CONTACTBDEB IS NOT NULL THEN L.VALORLCTOCTB ELSE 0 END) AS DEB,
           SUM(CASE WHEN L.CONTACTBCRED IS NOT NULL THEN L.VALORLCTOCTB ELSE 0 END) AS CRED,
           SUM(CASE WHEN L.CONTACTBDEB IS NULL OR L.CONTACTBCRED IS NULL THEN 1 ELSE 0 END) AS UM_LADO,
           COUNT(*) AS LINHAS
    FROM L WHERE L.CODIGOLOTECTB IS NOT NULL GROUP BY 1, 2
    UNION ALL
    SELECT 'TRANSCTB', CAST(L.TRANSCTB AS VARCHAR(40)),
           SUM(CASE WHEN L.CONTACTBDEB IS NOT NULL THEN L.VALORLCTOCTB ELSE 0 END),
           SUM(CASE WHEN L.CONTACTBCRED IS NOT NULL THEN L.VALORLCTOCTB ELSE 0 END),
           SUM(CASE WHEN L.CONTACTBDEB IS NULL OR L.CONTACTBCRED IS NULL THEN 1 ELSE 0 END), COUNT(*)
    FROM L WHERE L.TRANSCTB IS NOT NULL GROUP BY 1, 2
    UNION ALL
    SELECT 'CHAVEORIGEM', CAST(L.CHAVEORIGEM AS VARCHAR(40)),
           SUM(CASE WHEN L.CONTACTBDEB IS NOT NULL THEN L.VALORLCTOCTB ELSE 0 END),
           SUM(CASE WHEN L.CONTACTBCRED IS NOT NULL THEN L.VALORLCTOCTB ELSE 0 END),
           SUM(CASE WHEN L.CONTACTBDEB IS NULL OR L.CONTACTBCRED IS NULL THEN 1 ELSE 0 END), COUNT(*)
    FROM L WHERE L.CHAVEORIGEM IS NOT NULL AND TRIM(L.CHAVEORIGEM) <> '' GROUP BY 1, 2
    UNION ALL
    SELECT 'DATA+NUMERODCTO', CAST(L.DATALCTOCTB AS VARCHAR(12)) || '|' || TRIM(L.NUMERODCTO),
           SUM(CASE WHEN L.CONTACTBDEB IS NOT NULL THEN L.VALORLCTOCTB ELSE 0 END),
           SUM(CASE WHEN L.CONTACTBCRED IS NOT NULL THEN L.VALORLCTOCTB ELSE 0 END),
           SUM(CASE WHEN L.CONTACTBDEB IS NULL OR L.CONTACTBCRED IS NULL THEN 1 ELSE 0 END), COUNT(*)
    FROM L WHERE L.NUMERODCTO IS NOT NULL AND TRIM(L.NUMERODCTO) <> '' GROUP BY 1, 2
    UNION ALL
    SELECT 'DATAHORALCTOCTB', CAST(L.DATAHORALCTOCTB AS VARCHAR(30)),
           SUM(CASE WHEN L.CONTACTBDEB IS NOT NULL THEN L.VALORLCTOCTB ELSE 0 END),
           SUM(CASE WHEN L.CONTACTBCRED IS NOT NULL THEN L.VALORLCTOCTB ELSE 0 END),
           SUM(CASE WHEN L.CONTACTBDEB IS NULL OR L.CONTACTBCRED IS NULL THEN 1 ELSE 0 END), COUNT(*)
    FROM L GROUP BY 1, 2
)
SELECT
    G.CAMPO,
    COUNT(*) AS GRUPOS,
    SUM(CASE WHEN G.LINHAS > 1 THEN 1 ELSE 0 END) AS GRUPOS_COM_VARIAS_LINHAS,
    SUM(CASE WHEN G.UM_LADO > 0 THEN 1 ELSE 0 END) AS GRUPOS_COM_LINHA_DE_UM_LADO,
    SUM(CASE WHEN G.DEB = G.CRED THEN 1 ELSE 0 END) AS GRUPOS_FECHA,
    SUM(CASE WHEN G.DEB <> G.CRED THEN 1 ELSE 0 END) AS GRUPOS_NAO_FECHA,
    SUM(CASE WHEN G.UM_LADO > 0 AND G.DEB = G.CRED THEN 1 ELSE 0 END) AS UM_LADO_E_FECHA
FROM G
GROUP BY 1
ORDER BY 1;

