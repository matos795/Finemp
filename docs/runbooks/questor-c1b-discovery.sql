-- Q44 — HIPÓTESE de pai por prefixo: para cada conta com N pontos, quantas
--       contas com N-1 pontos são prefixo exato seguido de '.'?
--       (0 = sem pai compatível; 1 = pai único; >1 = ambíguo)
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP FROM RDB$DATABASE),
C AS (
    SELECT PE.CONTACTB, PE.TIPOCONTA, TRIM(PE.CLASSIFCONTA) AS CLASSIF,
           CHAR_LENGTH(TRIM(PE.CLASSIFCONTA)) - CHAR_LENGTH(REPLACE(TRIM(PE.CLASSIFCONTA), '.', '')) AS NIVEL
    FROM PLANOESPEC PE CROSS JOIN P
    WHERE PE.CODIGOEMPRESA = P.EMP
)
SELECT X.NIVEL, X.TIPOCONTA,
    CASE WHEN X.NIVEL = 0 THEN 'RAIZ' WHEN X.PAIS = 0 THEN 'SEM_PAI' WHEN X.PAIS = 1 THEN 'PAI_UNICO' ELSE 'PAI_AMBIGUO' END AS SITUACAO_PAI,
    COUNT(*) AS QTD_CONTAS
FROM (
    SELECT A.NIVEL, A.TIPOCONTA,
           (SELECT COUNT(*) FROM C B WHERE B.NIVEL = A.NIVEL - 1 AND A.CLASSIF STARTING WITH B.CLASSIF || '.') AS PAIS
    FROM C A
) X
GROUP BY 1, 2, 3
ORDER BY 1, 2, 3;

-- Q45 — TIPOCONTA x (tem filho por prefixo?) x (teve movimento no período?)
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP, DATE '1900-01-01' AS INI, DATE '1900-01-31' AS FIM FROM RDB$DATABASE),
C AS (
    SELECT PE.CONTACTB, PE.TIPOCONTA, TRIM(PE.CLASSIFCONTA) AS CLASSIF,
           CHAR_LENGTH(TRIM(PE.CLASSIFCONTA)) - CHAR_LENGTH(REPLACE(TRIM(PE.CLASSIFCONTA), '.', '')) AS NIVEL
    FROM PLANOESPEC PE CROSS JOIN P
    WHERE PE.CODIGOEMPRESA = P.EMP
),
OBS AS (
    SELECT L.CONTACTBDEB AS CONTA FROM LCTOCTB L CROSS JOIN P
    WHERE L.CODIGOEMPRESA = P.EMP AND L.DATALCTOCTB BETWEEN P.INI AND P.FIM AND L.CONTACTBDEB IS NOT NULL
    UNION
    SELECT L.CONTACTBCRED FROM LCTOCTB L CROSS JOIN P
    WHERE L.CODIGOEMPRESA = P.EMP AND L.DATALCTOCTB BETWEEN P.INI AND P.FIM AND L.CONTACTBCRED IS NOT NULL
)
SELECT X.TIPOCONTA, X.FILHOS, X.MOVIMENTO, COUNT(*) AS QTD_CONTAS
FROM (
    SELECT A.TIPOCONTA,
        CASE WHEN EXISTS (SELECT 1 FROM C B WHERE B.NIVEL = A.NIVEL + 1 AND B.CLASSIF STARTING WITH A.CLASSIF || '.')
             THEN 'TEM_FILHO' ELSE 'SEM_FILHO' END AS FILHOS,
        CASE WHEN EXISTS (SELECT 1 FROM OBS O WHERE O.CONTA = A.CONTACTB)
             THEN 'COM_MOVIMENTO' ELSE 'SEM_MOVIMENTO' END AS MOVIMENTO
    FROM C A
) X
GROUP BY 1, 2, 3
ORDER BY 1, 2, 3;

-- Q46 — vínculo conta -> DRE em PLANOESPECPLANODRE x PLANOESPEC.CODIGODRE/CONTADRE
