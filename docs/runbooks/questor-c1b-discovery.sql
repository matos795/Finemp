-- Q84 — DATAHORALCTOCTB x DATALCTOCTB: digitação no mês, depois do mês, antes
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP, DATE '1900-01-01' AS INI, DATE '1900-01-31' AS FIM FROM RDB$DATABASE)
SELECT
    CASE
        WHEN CAST(L.DATAHORALCTOCTB AS DATE) < L.DATALCTOCTB THEN '1_ANTES_DA_DATA'
        WHEN EXTRACT(YEAR FROM L.DATAHORALCTOCTB) = EXTRACT(YEAR FROM L.DATALCTOCTB)
         AND EXTRACT(MONTH FROM L.DATAHORALCTOCTB) = EXTRACT(MONTH FROM L.DATALCTOCTB) THEN '2_MESMO_MES'
        WHEN (EXTRACT(YEAR FROM L.DATAHORALCTOCTB) * 12 + EXTRACT(MONTH FROM L.DATAHORALCTOCTB))
           - (EXTRACT(YEAR FROM L.DATALCTOCTB) * 12 + EXTRACT(MONTH FROM L.DATALCTOCTB)) = 1 THEN '3_MES_SEGUINTE'
        WHEN (EXTRACT(YEAR FROM L.DATAHORALCTOCTB) * 12 + EXTRACT(MONTH FROM L.DATAHORALCTOCTB))
           - (EXTRACT(YEAR FROM L.DATALCTOCTB) * 12 + EXTRACT(MONTH FROM L.DATALCTOCTB)) <= 3 THEN '4_ATE_3_MESES_DEPOIS'
        ELSE '5_MAIS_DE_3_MESES_DEPOIS'
    END AS GRAVACAO_X_COMPETENCIA,
    COUNT(*) AS LINHAS
FROM LCTOCTB L
CROSS JOIN P
WHERE L.CODIGOEMPRESA = P.EMP
  AND L.DATALCTOCTB BETWEEN P.INI AND P.FIM
GROUP BY 1
ORDER BY 1;

