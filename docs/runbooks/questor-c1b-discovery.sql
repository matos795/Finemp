FROM (
    SELECT
        CASE WHEN L.CONTACTBDEB IS NOT NULL AND L.CONTACTBCRED IS NOT NULL THEN 'DEB_E_CRED'
             WHEN L.CONTACTBDEB IS NOT NULL THEN 'SO_DEB'
             WHEN L.CONTACTBCRED IS NOT NULL THEN 'SO_CRED'
             ELSE 'SEM_CONTA' END AS FORMATO,
        (SELECT COUNT(*) FROM LCTOCTBPARTICIPANTE X
          WHERE X.CODIGOEMPRESA = L.CODIGOEMPRESA AND X.CHAVELCTOCTB = L.CHAVELCTOCTB) AS REGISTROS_PARTICIPANTE
    FROM LCTOCTB L
    CROSS JOIN P
    WHERE L.CODIGOEMPRESA = P.EMP
      AND L.DATALCTOCTB BETWEEN P.INI AND P.FIM
) Y
GROUP BY 1, 2
ORDER BY 1, 2;

