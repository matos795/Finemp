-- Q30 — colunas das tabelas candidatas (posição, tipo, nulidade)
SELECT
    TRIM(RF.RDB$RELATION_NAME) AS TABELA,
    RF.RDB$FIELD_POSITION AS POSICAO,
    TRIM(RF.RDB$FIELD_NAME) AS COLUNA,
    CASE F.RDB$FIELD_TYPE
        WHEN 7 THEN CASE F.RDB$FIELD_SUB_TYPE WHEN 1 THEN 'NUMERIC' WHEN 2 THEN 'DECIMAL' ELSE 'SMALLINT' END
        WHEN 8 THEN CASE F.RDB$FIELD_SUB_TYPE WHEN 1 THEN 'NUMERIC' WHEN 2 THEN 'DECIMAL' ELSE 'INTEGER' END
        WHEN 16 THEN CASE F.RDB$FIELD_SUB_TYPE WHEN 1 THEN 'NUMERIC' WHEN 2 THEN 'DECIMAL' ELSE 'BIGINT' END
        WHEN 10 THEN 'FLOAT' WHEN 27 THEN 'DOUBLE PRECISION'
        WHEN 12 THEN 'DATE' WHEN 13 THEN 'TIME' WHEN 35 THEN 'TIMESTAMP'
        WHEN 14 THEN 'CHAR' WHEN 37 THEN 'VARCHAR' WHEN 40 THEN 'CSTRING'
        WHEN 261 THEN 'BLOB'
        ELSE 'TIPO_' || F.RDB$FIELD_TYPE
    END AS TIPO,
    F.RDB$FIELD_PRECISION AS PRECISAO,
    -F.RDB$FIELD_SCALE AS ESCALA,
    COALESCE(F.RDB$CHARACTER_LENGTH, F.RDB$FIELD_LENGTH) AS TAMANHO,
    CASE WHEN COALESCE(RF.RDB$NULL_FLAG, F.RDB$NULL_FLAG, 0) = 1 THEN 'NOT NULL' ELSE 'NULL' END AS NULO
FROM RDB$RELATION_FIELDS RF
JOIN RDB$FIELDS F ON F.RDB$FIELD_NAME = RF.RDB$FIELD_SOURCE
WHERE RF.RDB$RELATION_NAME IN (
    'SALDOCTB', 'SALDOCTBMENSAL', 'SALDOCTBMENSALHIST', 'EMPRESASALDOCTBHIST',
    'LCTOCTBEXCLUIDO', 'LCTOCTBPARTICIPANTE', 'LCTOGER', 'LCTOGEREXCLUIDO',
    'LOTECTB', 'ORIGEMLCTOCTB', 'CFGZERAMENTOCTB', 'ZERAMENTOGER', 'ZERAMENTOCTBMOEDA',
    'CENTROCUSTO', 'PLESPECCENCUS', 'PLESPECCENCUSRELAC', 'RATCENTROCUSTO',
    'DRE', 'DREDETALHE', 'CFGDRE', 'PLANOESPECPLANODRE')
ORDER BY 1, 2;

-- Q31 — PK/UNIQUE e índices das tabelas candidatas
SELECT
    TRIM(I.RDB$RELATION_NAME) AS TABELA,
    TRIM(I.RDB$INDEX_NAME) AS INDICE,
    COALESCE(I.RDB$UNIQUE_FLAG, 0) AS UNICO,
    COALESCE(I.RDB$INDEX_INACTIVE, 0) AS INATIVO,
    S.RDB$FIELD_POSITION AS ORDEM,
    TRIM(S.RDB$FIELD_NAME) AS COLUNA
FROM RDB$INDICES I
JOIN RDB$INDEX_SEGMENTS S ON S.RDB$INDEX_NAME = I.RDB$INDEX_NAME
WHERE I.RDB$RELATION_NAME IN (
    'SALDOCTB', 'SALDOCTBMENSAL', 'SALDOCTBMENSALHIST', 'EMPRESASALDOCTBHIST',
    'LCTOCTBEXCLUIDO', 'LCTOCTBPARTICIPANTE', 'LCTOGER', 'LCTOGEREXCLUIDO',
    'LOTECTB', 'ORIGEMLCTOCTB', 'CFGZERAMENTOCTB', 'ZERAMENTOGER',
    'CENTROCUSTO', 'PLESPECCENCUSRELAC', 'RATCENTROCUSTO',
    'DRE', 'DREDETALHE', 'CFGDRE', 'PLANOESPECPLANODRE')
ORDER BY 1, 2, 5;

-- Q32 — triggers (só nome e tipo, sem código) das tabelas de lançamento,
--       exclusão e centro de custo
SELECT
    TRIM(T.RDB$RELATION_NAME) AS TABELA,
    TRIM(T.RDB$TRIGGER_NAME) AS GATILHO,
    T.RDB$TRIGGER_TYPE AS TIPO_GATILHO,
    COALESCE(T.RDB$TRIGGER_INACTIVE, 0) AS INATIVO
FROM RDB$TRIGGERS T
WHERE T.RDB$RELATION_NAME IN ('LCTOCTBEXCLUIDO', 'LCTOGER', 'LCTOGEREXCLUIDO',
                              'LCTOCTBPARTICIPANTE', 'SALDOCTB', 'SALDOCTBMENSAL', 'LOTECTB')
  AND COALESCE(T.RDB$SYSTEM_FLAG, 0) = 0
ORDER BY 1, 2;

-- Q33 — tabelas de usuário que têm coluna de centro de custo junto com
--       chave de lançamento, lote ou conta (separar configuração de movimento)
SELECT
    TRIM(R.RDB$RELATION_NAME) AS TABELA,
    MAX(CASE WHEN RF.RDB$FIELD_NAME = 'CHAVELCTOCTB' THEN 1 ELSE 0 END) AS TEM_CHAVELCTOCTB,
    MAX(CASE WHEN RF.RDB$FIELD_NAME = 'CODIGOLOTECTB' THEN 1 ELSE 0 END) AS TEM_CODIGOLOTECTB,
    MAX(CASE WHEN RF.RDB$FIELD_NAME = 'CONTACTB' THEN 1 ELSE 0 END) AS TEM_CONTACTB,
    MAX(CASE WHEN RF.RDB$FIELD_NAME = 'CODIGOCENTROCUSTO' THEN 1 ELSE 0 END) AS TEM_CODIGOCENTROCUSTO
FROM RDB$RELATIONS R
JOIN RDB$RELATION_FIELDS RF ON RF.RDB$RELATION_NAME = R.RDB$RELATION_NAME
WHERE COALESCE(R.RDB$SYSTEM_FLAG, 0) = 0
GROUP BY R.RDB$RELATION_NAME
HAVING MAX(CASE WHEN RF.RDB$FIELD_NAME = 'CODIGOCENTROCUSTO' THEN 1 ELSE 0 END) = 1
   AND MAX(CASE WHEN RF.RDB$FIELD_NAME IN ('CHAVELCTOCTB', 'CODIGOLOTECTB', 'CONTACTB') THEN 1 ELSE 0 END) = 1
ORDER BY 2 DESC, 3 DESC, 1;

