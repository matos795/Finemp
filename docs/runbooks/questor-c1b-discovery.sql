-- Q54 — granularidade: pares (estab, conta, dia) com movimento no período
--       que têm linha em SALDOCTB / SALDOCTBMENSAL na mesma data
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP, DATE '1900-01-01' AS INI, DATE '1900-01-31' AS FIM FROM RDB$DATABASE),
M AS (
    SELECT L.CODIGOESTAB, L.CONTACTBDEB AS CONTA, L.DATALCTOCTB AS DIA FROM LCTOCTB L CROSS JOIN P
    WHERE L.CODIGOEMPRESA = P.EMP AND L.DATALCTOCTB BETWEEN P.INI AND P.FIM AND L.CONTACTBDEB IS NOT NULL
    UNION
    SELECT L.CODIGOESTAB, L.CONTACTBCRED, L.DATALCTOCTB FROM LCTOCTB L CROSS JOIN P
    WHERE L.CODIGOEMPRESA = P.EMP AND L.DATALCTOCTB BETWEEN P.INI AND P.FIM AND L.CONTACTBCRED IS NOT NULL
)
SELECT
    COUNT(*) AS PARES_COM_MOVIMENTO,
    SUM(CASE WHEN EXISTS (SELECT 1 FROM SALDOCTB S CROSS JOIN P WHERE S.CODIGOEMPRESA = P.EMP
            AND S.CODIGOESTAB = M.CODIGOESTAB AND S.CONTACTB = M.CONTA AND S.DATASALDO = M.DIA) THEN 1 ELSE 0 END) AS COM_SALDOCTB_NO_DIA,
    SUM(CASE WHEN EXISTS (SELECT 1 FROM SALDOCTBMENSAL S CROSS JOIN P WHERE S.CODIGOEMPRESA = P.EMP
            AND S.CODIGOESTAB = M.CODIGOESTAB AND S.CONTACTB = M.CONTA AND S.DATASALDO = M.DIA) THEN 1 ELSE 0 END) AS COM_MENSAL_NO_DIA,
    SUM(CASE WHEN EXISTS (SELECT 1 FROM SALDOCTBMENSAL S CROSS JOIN P WHERE S.CODIGOEMPRESA = P.EMP
            AND S.CODIGOESTAB = M.CODIGOESTAB AND S.CONTACTB = M.CONTA
            AND EXTRACT(YEAR FROM S.DATASALDO) = EXTRACT(YEAR FROM M.DIA)
            AND EXTRACT(MONTH FROM S.DATASALDO) = EXTRACT(MONTH FROM M.DIA)) THEN 1 ELSE 0 END) AS COM_MENSAL_NO_MES
FROM M;

