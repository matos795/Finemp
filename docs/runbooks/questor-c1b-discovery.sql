-- Q74 — LOTECTB dos lotes usados no período: situação, origem, cobertura
--       de datas e se VALORLOTECTB fecha com TODAS as linhas do lote
--       (inclusive as fora do período; só contagem)
WITH P AS (SELECT CAST(-1 AS INTEGER) AS EMP, DATE '1900-01-01' AS INI, DATE '1900-01-31' AS FIM FROM RDB$DATABASE),
K AS (
    SELECT DISTINCT L.CODIGOLOTECTB
    FROM LCTOCTB L CROSS JOIN P
    WHERE L.CODIGOEMPRESA = P.EMP AND L.DATALCTOCTB BETWEEN P.INI AND P.FIM AND L.CODIGOLOTECTB IS NOT NULL
),
U AS (
    SELECT L.CODIGOLOTECTB,
           SUM(CASE WHEN L.CONTACTBDEB IS NOT NULL THEN L.VALORLCTOCTB ELSE 0 END) AS DEB,
           SUM(CASE WHEN L.CONTACTBCRED IS NOT NULL THEN L.VALORLCTOCTB ELSE 0 END) AS CRED,
           MIN(L.DATALCTOCTB) AS D1, MAX(L.DATALCTOCTB) AS D2
    FROM LCTOCTB L CROSS JOIN P
    JOIN K ON K.CODIGOLOTECTB = L.CODIGOLOTECTB
    WHERE L.CODIGOEMPRESA = P.EMP
    GROUP BY L.CODIGOLOTECTB
)
SELECT
    T.SITUACAOLOTECTB,
    T.CODIGOORIGLCTOCTB,
    COUNT(*) AS QTD_LOTES,
    SUM(CASE WHEN U.D1 < P.INI OR U.D2 > P.FIM THEN 1 ELSE 0 END) AS LOTES_COM_LINHA_FORA_PERIODO,
    SUM(CASE WHEN U.D1 >= T.DATAINICIALLOTECTB AND U.D2 <= T.DATAFINALLOTECTB THEN 1 ELSE 0 END) AS LINHAS_DENTRO_DATAS_DO_LOTE,
    SUM(CASE WHEN T.VALORLOTECTB = U.DEB THEN 1 ELSE 0 END) AS VALOR_IGUAL_DEBITOS,
    SUM(CASE WHEN T.VALORLOTECTB = U.CRED THEN 1 ELSE 0 END) AS VALOR_IGUAL_CREDITOS,
    SUM(CASE WHEN T.VALORLOTECTB <> U.DEB AND T.VALORLOTECTB <> U.CRED THEN 1 ELSE 0 END) AS VALOR_DIFERENTE
FROM U
CROSS JOIN P
JOIN LOTECTB T ON T.CODIGOEMPRESA = P.EMP AND T.CODIGOLOTECTB = U.CODIGOLOTECTB
GROUP BY 1, 2
ORDER BY 3 DESC;

